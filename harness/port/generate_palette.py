#!/usr/bin/env python3
"""Generate the Rust neutral palette from the checked-in, source-hashed IR."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
INPUT = ROOT / 'harness/port/neutral-colors.json'
OUTPUT = ROOT / 'src/generated_palette.rs'


def color_expression(value):
    if not re.fullmatch(r'[0-9A-F]{8}', value):
        raise ValueError('invalid color literal')
    alpha, red, green, blue = (int(value[i:i+2], 16) for i in (0, 2, 4, 6))
    return f'Color32::from_rgba_unmultiplied({red}, {green}, {blue}, {alpha})'


def generate(data):
    expected = {'barrier', 'background', 'foreground', 'primary', 'primaryForeground', 'secondary',
                'secondaryForeground', 'muted', 'mutedForeground', 'destructive',
                'destructiveForeground', 'error', 'errorForeground', 'card', 'border'}
    lines = ['//! Generated by `harness/port/generate_palette.py`; do not edit manually.',
             '//! Values are adapted from Forui; see THIRD_PARTY_NOTICES.md.',
             'use crate::Theme;', 'use egui::Color32;', '']
    for mode, key in [('light', 'neutralLight'), ('dark', 'neutralDark')]:
        colors = data['schemes'][key]
        if set(colors) != expected:
            raise ValueError('unexpected palette fields')
        lines += [f'pub(super) fn {mode}() -> Theme {{', '    Theme {', f'        dark: {str(mode == "dark").lower()},']
        for field, value in colors.items():
            snake = re.sub(r'(?<!^)(?=[A-Z])', '_', field).lower()
            lines.append(f'        {snake}: {color_expression(value)},')
        # Non-color tokens are shared by both palettes and derived from the
        # palette's text colors; the desktop scale is the native default.
        lines.append('        typography: crate::theme::Typography::desktop(')
        lines.append(f'            {color_expression(colors["foreground"])},')
        lines.append(f'            {color_expression(colors["mutedForeground"])},')
        lines.append('        ),')
        lines.append('        sizes: crate::tokens::Sizes::desktop(),')
        lines.append('        breakpoints: crate::tokens::Breakpoints::default(),')
        lines.append('        motion: crate::theme::MotionSettings::default(),')
        lines.append('        touch: false,')
        lines.append('        disabled_opacity: 0.5,')
        lines += ['    }', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(json.loads(INPUT.read_text()))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != output:
            print('generated palette differs from IR', file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(output)
    return 0


if __name__ == '__main__':
    sys.exit(main())
